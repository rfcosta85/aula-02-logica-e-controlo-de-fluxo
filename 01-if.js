let diaSemana = new Date();

numeroSemana = diaSemana.getDay();


if(numeroSemana == 1) {
    console.log("Segunda Feira");
}

if (numeroSemana == 2) {
    console.log("Terça Feira");
}

if(numeroSemana == 3) {
    console.log("Quarta Feira");
}

if(numeroSemana == 4) {
    console.log("Quinta Feira");
}

if(numeroSemana == 5) {
    console.log("Sexta Feira");
}

if(numeroSemana == 6) {
    console.log("Sábado");
}

if(numeroSemana == 7) {
    console.log("Domingo");
}